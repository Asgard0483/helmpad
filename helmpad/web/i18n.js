const STRINGS = {de, en, es, fr, it, hr};
let lang = 'de';

export function detectLang() {
  try {
    const saved = localStorage.getItem('helmpad.sprache');
    if (saved && STRINGS[saved]) return saved;
  } catch {}
  const nav = (navigator.language || 'de').slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : 'de';
}

export function setLang(code) {
  lang = STRINGS[code] ? code : 'de';
  document.documentElement.lang = lang;
  try { localStorage.setItem('helmpad.sprache', lang); } catch {}
}

export const getLang = () => lang;

/** Text zum Schlüssel, Platzhalter {name} aus `vars`; fehlt eine Übersetzung, gilt Deutsch. */
export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? de[key];
  if (s === undefined) return key;
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

/** Alle statischen Texte der Seite übersetzen (data-i18n = Inhalt, -title, -ph = Platzhalter). */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

/** Polstername der Vorlagen (z.B. "seite_rechts") in die aktuelle Sprache übertragen. */
export function zoneName(name) {
  return name.split('_').map(w => (de['zw.' + w] !== undefined ? t('zw.' + w) : w)).join('_');
}
